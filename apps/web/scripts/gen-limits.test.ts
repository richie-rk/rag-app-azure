// @vitest-environment node
import { spawnSync } from "node:child_process";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

import { describe, expect, test } from "vitest";

const SCRIPT = resolve(import.meta.dirname, "gen-limits.mjs");

/** Runs the script in a copy of the repository layout around a small OpenAPI document. */
function generate(document: unknown): string {
  const root = mkdtempSync(join(tmpdir(), "docchat-gen-limits-"));
  mkdirSync(join(root, "apps", "web", "scripts"), { recursive: true });
  mkdirSync(join(root, "apps", "web", "src", "api", "generated"), { recursive: true });
  mkdirSync(join(root, "apps", "api"), { recursive: true });
  copyFileSync(SCRIPT, join(root, "apps", "web", "scripts", "gen-limits.mjs"));
  writeFileSync(join(root, "apps", "api", "openapi.json"), JSON.stringify(document));
  const result = spawnSync(
    process.execPath,
    [join(root, "apps", "web", "scripts", "gen-limits.mjs")],
    {
      encoding: "utf8",
    },
  );
  expect(result.status).toBe(0);
  return readFileSync(
    join(root, "apps", "web", "src", "api", "generated", "limits.gen.ts"),
    "utf8",
  );
}

describe("gen-limits", () => {
  test("writes one constant per request-body field with a limit, nested schemas included", () => {
    const output = generate({
      paths: {
        "/a": {
          post: {
            requestBody: {
              content: {
                "application/json": { schema: { $ref: "#/components/schemas/ThingCreate" } },
              },
            },
          },
          get: {},
        },
      },
      components: {
        schemas: {
          ThingCreate: {
            type: "object",
            properties: {
              name: { type: "string", maxLength: 80, minLength: 1 },
              note: { anyOf: [{ type: "string", maxLength: 400 }, { type: "null" }] },
              tags: { type: "array", maxItems: 4, items: { type: "string", maxLength: 160 } },
              parts: { type: "array", maxItems: 2, items: { $ref: "#/components/schemas/Part" } },
              count: { type: "integer", minimum: 1, maximum: 10 },
              flag: { type: "boolean" },
              choice: { anyOf: [{ type: "string" }, { type: "integer" }] },
            },
          },
          Part: { type: "object", properties: { size: { type: "integer", maximum: 5 } } },
          Unused: { type: "object", properties: { x: { type: "string", maxLength: 1 } } },
        },
      },
    });
    expect(output).toContain(
      '/** `ThingCreate.name` */\nexport const thingCreateName = {"maxLength":80} as const;',
    );
    expect(output).toContain('export const thingCreateNote = {"maxLength":400} as const;');
    expect(output).toContain(
      'export const thingCreateTags = {"maxItems":4,"itemsMaxLength":160} as const;',
    );
    expect(output).toContain('export const thingCreateParts = {"maxItems":2} as const;');
    expect(output).toContain(
      'export const thingCreateCount = {"minimum":1,"maximum":10} as const;',
    );
    expect(output).toContain('export const partSize = {"maximum":5} as const;');
    expect(output).not.toContain("thingCreateFlag");
    expect(output).not.toContain("thingCreateChoice");
    expect(output).not.toContain("unused");
    expect(output.startsWith("// This file is generated by scripts/gen-limits.mjs")).toBe(true);
  });

  test("the committed limits hold the form limits the screens use", () => {
    const committed = readFileSync(
      resolve(import.meta.dirname, "..", "src", "api", "generated", "limits.gen.ts"),
      "utf8",
    );
    expect(committed).toContain(
      "export const memoryFactRequestText = { maxLength: 800 } as const;",
    );
    expect(committed).toContain(
      "export const projectCreateExampleQuestions = { maxItems: 4, itemsMaxLength: 160 } as const;",
    );
    expect(committed).toContain("export const projectCreateName = { maxLength: 80 } as const;");
  });
});
