#!/usr/bin/env node
// Writes src/api/generated/limits.gen.ts from apps/api/openapi.json (10-web-client.md section
// 5.1): one constant per field of every JSON request body, holding the limits the API validates,
// so form limits come from the same source as the API's validation. Node.js standard library
// only; `npm run generate:api` formats the output with Prettier.

import { readFileSync, writeFileSync } from "node:fs";

const DOCUMENT = new URL("../../api/openapi.json", import.meta.url);
const OUTPUT = new URL("../src/api/generated/limits.gen.ts", import.meta.url);
const KEYWORDS = ["maxLength", "maxItems", "minimum", "maximum"];

function schemaName(reference) {
  return reference.split("/").pop();
}

/** The non-null branch of a nullable `anyOf`, or the schema itself. */
function unwrapNullable(schema) {
  if (Array.isArray(schema.anyOf)) {
    const branches = schema.anyOf.filter((branch) => branch.type !== "null");
    if (branches.length === 1) return branches[0];
  }
  return schema;
}

function camel(...parts) {
  const words = parts
    .join(" ")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean);
  return words
    .map((word, index) =>
      index === 0
        ? word.charAt(0).toLowerCase() + word.slice(1)
        : word.charAt(0).toUpperCase() + word.slice(1),
    )
    .join("");
}

function limitsOf(schema, schemas) {
  const resolved = unwrapNullable(schema.$ref ? schemas[schemaName(schema.$ref)] : schema);
  const limits = {};
  for (const keyword of KEYWORDS) {
    if (typeof resolved[keyword] === "number") limits[keyword] = resolved[keyword];
  }
  if (resolved.type === "array" && resolved.items && !resolved.items.$ref) {
    const items = unwrapNullable(resolved.items);
    if (typeof items.maxLength === "number") limits.itemsMaxLength = items.maxLength;
  }
  return limits;
}

/** Request-body schemas, and the object schemas their arrays and properties refer to. */
function requestSchemas(document) {
  const schemas = document.components.schemas;
  const names = new Set();
  const pending = [];
  for (const operations of Object.values(document.paths)) {
    for (const operation of Object.values(operations)) {
      const reference = operation.requestBody?.content?.["application/json"]?.schema?.$ref;
      if (reference) pending.push(schemaName(reference));
    }
  }
  while (pending.length > 0) {
    const name = pending.pop();
    if (names.has(name)) continue;
    names.add(name);
    for (const property of Object.values(schemas[name].properties ?? {})) {
      const nested = property.$ref ?? property.items?.$ref;
      if (nested && schemas[schemaName(nested)].type === "object") pending.push(schemaName(nested));
    }
  }
  return [...names].sort();
}

function render(document) {
  const schemas = document.components.schemas;
  const lines = [
    "// This file is generated by scripts/gen-limits.mjs from apps/api/openapi.json; don't edit it.",
    "",
  ];
  for (const name of requestSchemas(document)) {
    const properties = schemas[name].properties ?? {};
    for (const field of Object.keys(properties).sort()) {
      const limits = limitsOf(properties[field], schemas);
      if (Object.keys(limits).length === 0) continue;
      lines.push(`/** \`${name}.${field}\` */`);
      lines.push(`export const ${camel(name, field)} = ${JSON.stringify(limits)} as const;`);
      lines.push("");
    }
  }
  return lines.join("\n");
}

writeFileSync(OUTPUT, render(JSON.parse(readFileSync(DOCUMENT, "utf8"))), "utf8");
