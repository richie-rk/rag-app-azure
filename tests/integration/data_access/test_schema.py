def test_t071_included_columns_equal_the_metadata(admin: Engine) -> None:
    # `alembic check` compares an index's key columns but not its `INCLUDE` list.
    with admin.connect() as connection:
        rows = connection.exec_driver_sql(
            "SELECT i.name AS index_name, c.name AS column_name "
            "FROM sys.indexes AS i "
            "JOIN sys.index_columns AS ic "
            "ON ic.object_id = i.object_id AND ic.index_id = i.index_id "
            "JOIN sys.columns AS c ON c.object_id = ic.object_id AND c.column_id = ic.column_id "
            "WHERE ic.is_included_column = 1 AND OBJECT_SCHEMA_NAME(i.object_id) = 'app' "
            "ORDER BY i.name, ic.index_column_id"
        ).all()
    included: dict[str, set[str]] = {}
    for row in rows:
        included.setdefault(row.index_name, set()).add(row.column_name)
    expected = {
        str(index.name): {str(column) for column in index.dialect_options["mssql"]["include"]}
        for table in metadata.tables.values()
        for index in table.indexes
        if index.dialect_options["mssql"]["include"]
    }
    assert included == expected


def test_t071_schema_inventory(admin: Engine) -> None:
    with admin.connect() as connection:
        tables = connection.exec_driver_sql(
            "SELECT t.name FROM sys.tables AS t WHERE t.schema_id = SCHEMA_ID('app')"
        ).scalars()
        assert len(set(tables)) == 18
        keys = connection.exec_driver_sql(
            "SELECT name, delete_referential_action_desc, is_not_trusted, is_disabled "
            "FROM sys.foreign_keys WHERE schema_id = SCHEMA_ID('app')"
        ).all()
        assert len(keys) == 30
        assert {row.name for row in keys if row.delete_referential_action_desc == "CASCADE"} == {
            "FK_project_members_users",
            "FK_user_index_overrides_users",
            "FK_user_index_overrides_mapping",
        }
        assert not any(row.is_not_trusted or row.is_disabled for row in keys)
        triggers = connection.exec_driver_sql(
            "SELECT name, OBJECT_DEFINITION(object_id) AS body FROM sys.triggers "
            "WHERE parent_id IN "
            "(SELECT object_id FROM sys.tables WHERE schema_id = SCHEMA_ID('app'))"
        ).all()
    assert [row.name for row in triggers] == ["trg_document_versions_scan_insert"]
    block = re.search(
        r"```sql\n(CREATE TRIGGER app\.trg_document_versions_scan_insert.*?)\n```",
        spec("80-data-model.md"),
        re.S,
    )
    assert block is not None
    assert triggers[0].body.strip() == block.group(1).strip()


def test_a02_filtered_unique_index_and_rowversion(admin: Engine) -> None:
    with rolled_back(admin) as connection:
        project_id = new_project(connection)
        first, second = new_index(connection), new_index(connection)
        mapping = {"project_id": project_id, "created_by": ADMIN, "updated_by": ADMIN}
        connection.execute(
            insert(project_indexes).values(search_index_id=first, is_default=True, **mapping)
        )
        # The filter leaves non-default mappings out, so any number of them is allowed ...
        connection.execute(
            insert(project_indexes).values(search_index_id=second, is_default=False, **mapping)
        )
        # ... while a second default for the project is refused.
        third = new_index(connection)
        nested = connection.begin_nested()
        number = error_number(
            lambda: connection.execute(
                insert(project_indexes).values(search_index_id=third, is_default=True, **mapping)
            )
        )
        nested.rollback()
        assert number == 2601
        before = connection.execute(
            select(projects.c.row_version).where(projects.c.id == project_id)
        ).scalar_one()
        connection.execute(
            update(projects).where(projects.c.id == project_id).values(description="changed")
        )
        after = connection.execute(
            select(projects.c.row_version).where(projects.c.id == project_id)
        ).scalar_one()
        assert len(before) == len(after) == 8
        assert after != before


def test_t075_constraints(admin: Engine) -> None:
    with rolled_back(admin) as connection:

        def refused(statement: Any) -> int:
            nested = connection.begin_nested()
            number = error_number(lambda: connection.execute(statement))
            nested.rollback()
            return number

        assert (
            refused(
                insert(projects).values(
                    id=uuid.uuid4(), name="x", status="paused", created_by=ADMIN, updated_by=ADMIN
                )
            )
            == 547
        )
        assert refused(insert(ingestion_dispatcher_state).values(id=2)) == 547
        assert refused(insert(ingestion_dispatcher_state).values(id=1)) == 2627
        new_project(connection, name="Same Name")
        assert (
            refused(
                insert(projects).values(
                    id=uuid.uuid4(), name="same name", created_by=ADMIN, updated_by=ADMIN
                )
            )
            == 2627
        )
        assert (
            refused(
                insert(ops_config).values(
                    config_key="Not.Lower", value_json='{"value":1}', default_json='{"value":1}'
                )
            )
            == 547
        )


def test_t128_scan_columns_start_at_their_initial_values(
    admin: Engine, role_engines: dict[str, Engine]
) -> None:
    with admin.begin() as connection:
        project_id = new_project(connection)
        index_id = new_index(connection)
        document_id = new_document(connection, index_id)
    api = role_engines["docchat_api"]
    forged: list[dict[str, Any]] = [
        {"scan_required": True, "scan_status": "clean"},
        {"scan_required": False, "scan_status": "malicious"},
        {"scan_required": False, "scan_status": "failed"},
        {"scan_required": False, "scan_status": "unavailable"},
        {"scan_required": False, "scan_status": "awaiting"},
        {"scan_required": True, "scan_status": "not_required"},
        {"scan_time": "2026-10-30T00:00:00"},
        {"scan_raw_result": "x"},
        {"converter_version": "lo"},
        {
            "content_type": (
                "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
            ),
            "converted_sha256": b"\x01" * 32,
        },
        {"document_pdf_status": "built"},
    ]
    for number, extra in enumerate(forged, start=1):
        row = version_row(document_id, index_id, project_id, version_number=number, **extra)
        with api.connect() as connection:
            statement = insert(document_versions).values(**row)
            assert error_number(partial(connection.execute, statement)) == 51010
    with api.connect() as connection:
        good = version_row(document_id, index_id, project_id, version_number=50)
        bad = version_row(
            document_id,
            index_id,
            project_id,
            version_number=51,
            scan_status="clean",
            scan_required=True,
        )
        assert (
            error_number(lambda: connection.execute(insert(document_versions), [good, bad]))
            == 51010
        )
    with admin.connect() as connection:
        count = connection.execute(
            select(func.count())
            .select_from(document_versions)
            .where(document_versions.c.document_id == document_id)
        ).scalar_one()
        assert count == 0
        assert (
            error_number(
                lambda: connection.exec_driver_sql(
                    "INSERT INTO app.document_versions (id) OUTPUT inserted.id VALUES (NEWID())"
                )
            )
            == 334
        )
    with api.begin() as connection:
        connection.execute(
            insert(document_versions).values(
                **version_row(document_id, index_id, project_id, version_number=60)
            )
        )
        connection.execute(
            insert(document_versions).values(
                **version_row(
                    document_id,
                    index_id,
                    project_id,
                    version_number=61,
                    scan_required=True,
                    scan_status="awaiting",
                )
            )
        )


