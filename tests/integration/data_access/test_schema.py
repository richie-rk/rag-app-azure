def spec(name: str) -> str:
    for parent in Path(__file__).resolve().parents:
        candidate = parent / "docs" / "spec" / name
        if candidate.is_file():
            return candidate.read_text(encoding="utf-8")
    raise FileNotFoundError(name)


@contextmanager
def rolled_back(engine: Engine) -> Iterator[Connection]:
    """A connection whose work is undone, so each test leaves the seeded database as it was."""
    with engine.connect() as connection:
        transaction = connection.begin()
        try:
            yield connection
        finally:
            transaction.rollback()


def error_number(action: Callable[[], object]) -> int:
    """The SQL Server error number `action` fails with; 0 when it succeeds."""
    try:
        action()
    except DBAPIError as error:
        driver = driver_error_of(error)
        assert driver is not None
        return describe_driver_error(driver).number
    return 0


