def test_t087_a_changed_default_keeps_an_operators_value(admin: Engine) -> None:
    # The statement a default-change revision runs (80-data-model.md section 2.24).
    change = (
        "UPDATE app.ops_config SET value_json = CASE WHEN value_json = default_json THEN ? "
        "ELSE value_json END, default_json = ? WHERE config_key = ?"
    )
    with rolled_back(admin) as connection:
        connection.execute(
            update(ops_config)
            .where(ops_config.c.config_key == "memory.max_facts")
            .values(value_json='{"value":80}', change_reason="operator change", updated_by=ADMIN)
        )
        for key, new in (
            ("memory.max_facts", '{"value":60}'),
            ("memory.max_tokens", '{"value":1500}'),
        ):
            connection.exec_driver_sql(change, (new, new, key))
        values = dict(
            connection.execute(
                select(ops_config.c.config_key, ops_config.c.value_json).where(
                    ops_config.c.config_key.in_(["memory.max_facts", "memory.max_tokens"])
                )
            ).all()
        )
    assert values == {"memory.max_facts": '{"value":80}', "memory.max_tokens": '{"value":1500}'}


